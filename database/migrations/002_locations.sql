-- 002_locations: upazilas + unions
CREATE TABLE IF NOT EXISTS upazilas (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name_en VARCHAR(100) NOT NULL,
  name_bn VARCHAR(100) NULL,
  district VARCHAR(100) NOT NULL DEFAULT 'Bogura',
  division VARCHAR(100) NOT NULL DEFAULT 'Rajshahi',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_upazilas_name (name_en, district)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS unions (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  upazila_id INT UNSIGNED NOT NULL,
  name_en VARCHAR(100) NOT NULL,
  name_bn VARCHAR(100) NULL,
  code VARCHAR(50) NULL,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_unions_upazila FOREIGN KEY (upazila_id) REFERENCES upazilas(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  UNIQUE KEY uq_unions_code (code),
  KEY idx_unions_upazila (upazila_id),
  KEY idx_unions_active (is_active)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
