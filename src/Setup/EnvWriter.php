<?php
declare(strict_types=1);

/**
 * Safe .env handling. Never overwrites an existing file; never logs file
 * contents. chmod 0600 is best-effort (verified with fileperms readback and
 * reported when not achievable on the host).
 */
final class EnvWriter
{
    /** Render .env text in .env.example key order with the given DB values. */
    public static function render(
        string $host,
        string $port,
        string $name,
        string $user,
        string $pass,
        string $charset = 'utf8mb4'
    ): string {
        $lines = [
            '# Sonatola Upazila Digital Platform — generated by setup.php (DO NOT COMMIT)',
            'APP_ENV=production',
            'APP_DEBUG=false',
            'APP_URL=https://example.gov.bd',
            'APP_KEY=' . bin2hex(random_bytes(24)),
            '',
            '# Database (MySQL/MariaDB)',
            'DB_HOST=' . self::escape($host),
            'DB_PORT=' . self::escape($port),
            'DB_NAME=' . self::escape($name),
            'DB_USER=' . self::escape($user),
            'DB_PASS=' . self::escape($pass),
            'DB_CHARSET=' . self::escape($charset),
            '',
            '# Sessions / cookies',
            'SESSION_NAME=sonatola_sid',
            'COOKIE_SECURE=true',
            'COOKIE_SAMESITE=Lax',
            'SESSION_IDLE_MINUTES=120',
            'SESSION_ABSOLUTE_HOURS=12',
            '',
            '# Password reset stays disabled until SMTP is configured.',
            'PASSWORD_RESET_ENABLED=false',
            '',
            '# CORS (comma separated origins, empty = same-origin only)',
            'CORS_ALLOWED_ORIGINS=',
            '',
            '# Uploads',
            'UPLOAD_MAX_MB=5',
            'UPLOAD_DIR=../storage/uploads',
            '',
            '# Rate limiting',
            'LOGIN_MAX_ATTEMPTS=5',
            'LOGIN_LOCKOUT_MINUTES=15',
            'API_RATE_PER_MINUTE=60',
            '',
            '# First admin bootstrap is via CLI only (scripts/create_admin.php), no seeded admin.',
            '',
        ];
        return implode("\n", $lines);
    }

    /**
     * Atomically write .env (temp + rename). Refuses when .env already exists.
     * @return array{chmod_ok:bool} chmod result is best-effort — caller must report it.
     * @throws AppException when .env exists or the write fails (messages contain no secrets)
     */
    public static function write(string $projectRoot, string $content): array
    {
        $dest = rtrim($projectRoot, '/') . '/.env';
        if (is_file($dest)) {
            throw AppException::forbidden(
                'A .env file already exists. It was not overwritten. ' .
                'Back it up or remove it via the hosting File Manager, then reload setup.'
            );
        }
        $tmp = $dest . '.tmp-' . bin2hex(random_bytes(8));
        if (@file_put_contents($tmp, $content, LOCK_EX) === false) {
            throw new AppException('Could not write configuration file. Check directory permissions.', 500);
        }
        @chmod($tmp, 0600);
        if (!@rename($tmp, $dest)) {
            @unlink($tmp);
            throw new AppException('Could not install configuration file. Check directory permissions.', 500);
        }
        @chmod($dest, 0600);
        $perms = @fileperms($dest);
        $chmodOk = $perms !== false && (($perms & 0777) === 0600);
        return ['chmod_ok' => $chmodOk];
    }

    private static function escape(string $v): string
    {
        // Quote only when the value contains characters unsafe for bare .env values.
        if (preg_match('/[^A-Za-z0-9_.\-:\/]/', $v)) {
            return "'" . str_replace("'", "'\\''", $v) . "'";
        }
        return $v;
    }
}
